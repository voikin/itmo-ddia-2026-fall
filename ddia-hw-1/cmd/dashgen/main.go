package main

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"log/slog"
	"net/http"
	"os"
	"time"

	goapi "github.com/grafana/grafana-openapi-client-go/client"
	"github.com/grafana/grafana-openapi-client-go/models"

	"github.com/voikin/itmo-ddia-2026-fall/ddia-hw-1/internal/dashboard"
	"github.com/voikin/itmo-ddia-2026-fall/ddia-hw-1/internal/grafana"
	"github.com/voikin/itmo-ddia-2026-fall/ddia-hw-1/pkg/metrics"
)

func main() {
	slog.SetDefault(slog.New(slog.NewJSONHandler(os.Stdout, nil)))
	if err := run(); err != nil {
		slog.Error("dashgen failed", "err", err)
		os.Exit(1)
	}
}

func run() error {
	tokenFile, err := grafana.MustEnv("GRAFANA_TOKEN_FILE")
	if err != nil {
		return err
	}
	token, err := grafana.ReadSecretFile(tokenFile)
	if err != nil {
		return err
	}
	appURL := grafana.Env("APP_URL", "http://app:8080")
	deployment := grafana.Env("DEPLOYMENT", "items-service")

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()

	routes, err := fetchRoutes(ctx, appURL)
	if err != nil {
		return err
	}
	slog.Info("routes discovered", "app", appURL, "routes", routes)

	d, err := dashboard.Build(dashboard.Config{
		UID:           grafana.Env("DASHBOARD_UID", deployment+"-golden-signals"),
		Title:         deployment + " golden signals",
		DatasourceUID: grafana.Env("DATASOURCE_UID", "victoriametrics"),
		Deployment:    deployment,
	}, routes)
	if err != nil {
		return fmt.Errorf("build dashboard: %w", err)
	}

	c, err := grafana.NewClient(grafana.Env("GRAFANA_URL", "http://grafana:3000"), grafana.Auth{Token: token})
	if err != nil {
		return err
	}
	if err := grafana.WaitHealthy(ctx, c); err != nil {
		return err
	}

	folderUID := grafana.Env("FOLDER_UID", "generated")
	if err := ensureFolder(c, folderUID, grafana.Env("FOLDER_TITLE", "Generated")); err != nil {
		return err
	}

	resp, err := c.Dashboards.PostDashboard(&models.SaveDashboardCommand{
		Dashboard: d,
		FolderUID: folderUID,
		Overwrite: true,
		Message:   fmt.Sprintf("generated by dashgen from %s/routes", appURL),
	})
	if err != nil {
		return fmt.Errorf("save dashboard: %w", err)
	}
	slog.Info("dashboard saved", "uid", *resp.Payload.UID, "url", *resp.Payload.URL, "version", *resp.Payload.Version)
	return nil
}

func fetchRoutes(ctx context.Context, appURL string) ([]metrics.Route, error) {
	client := http.Client{Timeout: 5 * time.Second}
	for {
		routes, err := getRoutes(ctx, &client, appURL+"/routes")
		if err == nil {
			return routes, nil
		}
		slog.Warn("routes are not available yet", "err", err)
		select {
		case <-ctx.Done():
			return nil, fmt.Errorf("fetch routes: %w (last error: %v)", ctx.Err(), err)
		case <-time.After(2 * time.Second):
		}
	}
}

func getRoutes(ctx context.Context, client *http.Client, url string) ([]metrics.Route, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: status %d", url, resp.StatusCode)
	}
	var routes []metrics.Route
	if err := json.NewDecoder(resp.Body).Decode(&routes); err != nil {
		return nil, fmt.Errorf("decode routes: %w", err)
	}
	if len(routes) == 0 {
		return nil, errors.New("application reported no routes")
	}
	return routes, nil
}

func ensureFolder(c *goapi.GrafanaHTTPAPI, uid, title string) error {
	_, err := c.Folders.CreateFolder(&models.CreateFolderCommand{UID: uid, Title: title})
	if err == nil {
		return nil
	}
	if _, getErr := c.Folders.GetFolderByUID(uid); getErr == nil {
		return nil
	}
	return fmt.Errorf("create folder %s: %w", uid, err)
}
